// Define the Momentum with Bollinger Bands Indicator
describe_indicator('Momentum with Bollinger Bands v2', 'lower', {
    shortName: 'MoBB',
    decimals: 2
});

const momentumLength = input('Momentum Length', 14, { min: 1, max: 100 });
const bbLength = input('Bollinger Band Length', 20, { min: 1, max: 100 });
const bbMultiplier = input('Bollinger Bands Multiplier', 2, { min: 1, max: 5 });

// Calculate the Momentum
const momentumValues = close.map((value, index) => {
    if (index < momentumLength) return null;
    return value - close[index - momentumLength];
});

// Calculate Simple Moving Average (SMA)
function calculateSMA(data, length) {
    let smaValues = [];
    for (let i = 0; i < data.length; i++) {
        if (i < length - 1) {
            smaValues.push(null);
        } else {
            let sumValues = 0;
            for (let j = 0; j < length; j++) {
                sumValues += data[i - j];
            }
            smaValues.push(sumValues / length);
        }
    }
    return smaValues;
}

// Calculate Standard Deviation (StdDev)
function calculateStdDev(data, length) {
    let stddevValues = [];
    let smaValues = calculateSMA(data, length);
    for (let i = 0; i < data.length; i++) {
        if (i < length - 1) {
            stddevValues.push(null);
        } else {
            let sumDiffs = 0;
            for (let j = 0; j < length; j++) {
                sumDiffs += Math.pow(data[i - j] - smaValues[i], 2);
            }
            stddevValues.push(Math.sqrt(sumDiffs / length));
        }
    }
    return stddevValues;
}

// Calculate Bollinger Bands around the Momentum
const smaMomentum = calculateSMA(momentumValues, bbLength);
const stdDevMomentum = calculateStdDev(momentumValues, bbLength);
const upperBand = smaMomentum.map((v, i) => v !== null ? v + bbMultiplier * stdDevMomentum[i] : null);
const lowerBand = smaMomentum.map((v, i) => v !== null ? v - bbMultiplier * stdDevMomentum[i] : null);

// Determine colors for the Momentum line
const momentumColors = momentumValues.map((value, index) => {
    if (value === null) return null;
    if (value < lowerBand[index]) return 'green';
    if (value > upperBand[index]) return 'red';
    return 'black';
});

// Paint the Momentum line with dynamic colors
const paintedMomentum = paint(momentumValues, {
    name: 'Momentum',
    color: momentumColors,
    thickness: 2
});

// Paint the Bollinger Bands
const paintedUpperBand = paint(upperBand, { name: 'Upper Band', color: 'gray', thickness: 1 });
const paintedLowerBand = paint(lowerBand, { name: 'Lower Band', color: 'gray', thickness: 1 });

// Shade areas when momentum is outside Bollinger Bands
fill(paintedMomentum, paintedUpperBand, 'rgba(255, 0, 0, 0.1)');
fill(paintedMomentum, paintedLowerBand, 'rgba(0, 255, 0, 0.1)');
